import { spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
const exe = path.join(os.homedir(), '.codeartsdoer', 'installers', 'bin', 'codearts.exe');
const t0 = Date.now();
const r = spawnSync(exe, ['--version'], { encoding: 'utf8', timeout: 20000, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
console.log('ms:', Date.now() - t0, 'status:', r.status, 'signal:', r.signal);
console.log('out:', JSON.stringify((r.stdout || '').slice(0, 200)));
console.log('err:', JSON.stringify((r.stderr || '').slice(0, 200)));
console.log('error:', r.error ? r.error.message : 'none');
